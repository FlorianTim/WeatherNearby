// Checks every resolved dependency against the OSV.dev vulnerability database
// and reports the ones that need a security update.
//
// Run from the repo root (wrappers: scripts/deps/audit.sh|ps1):
//   dart tools/audit_deps.dart [options]
//
// Options:
//   --fix        upgrade the affected packages afterwards (dart pub upgrade)
//   --outdated   additionally show how far behind the whole tree is
//   --json       machine-readable output (for CI annotations)
//   --offline    skip the OSV query, only run the local checks
//
// Exit codes: 0 = clean, 1 = vulnerabilities found, 2 = tool error.
//
// Why OSV.dev: it is the only free, public database that indexes the Pub
// ecosystem, it needs no API key, and only package names plus versions leave
// the machine - the same data that is public in pubspec.lock anyway.

import 'dart:convert';
import 'dart:io';

const _osvBatchUrl = 'https://api.osv.dev/v1/querybatch';
const _osvVulnUrl = 'https://api.osv.dev/v1/vulns/';

/// One hosted package as resolved in pubspec.lock.
class Package {
  Package(this.name, this.version, this.dependency);

  final String name;
  final String version;
  final String dependency; // direct main | direct dev | transitive
}

/// A vulnerability affecting one resolved package.
class Finding {
  Finding({
    required this.package,
    required this.id,
    required this.summary,
    required this.severity,
    required this.fixedIn,
    required this.aliases,
  });

  final Package package;
  final String id;
  final String summary;
  final String severity;
  final String? fixedIn;
  final List<String> aliases;
}

bool jsonOutput = false;

Future<void> main(List<String> args) async {
  exitCode = await _run(args);
}

Future<int> _run(List<String> args) async {
  final fix = args.contains('--fix');
  final outdated = args.contains('--outdated');
  final offline = args.contains('--offline');
  jsonOutput = args.contains('--json');

  if (!File('pubspec.lock').existsSync()) {
    stderr.writeln(
      'pubspec.lock not found. Run this from the repository root '
      '(or run "melos bs" first).',
    );
    return 2;
  }

  final packages = parseLockFile(File('pubspec.lock').readAsStringSync());
  _log('Resolved hosted packages: ${packages.length}');

  var findings = <Finding>[];
  if (offline) {
    _log('--offline: skipping the OSV.dev query.');
  } else {
    try {
      findings = await queryOsv(packages);
    } on SocketException catch (e) {
      stderr.writeln('Could not reach api.osv.dev: ${e.message}');
      stderr.writeln('Re-run with --offline to skip the vulnerability check.');
      return 2;
    }
  }

  if (jsonOutput) {
    stdout.writeln(
      const JsonEncoder.withIndent('  ').convert({
        'scanned': packages.length,
        'vulnerable': findings.length,
        'findings': [
          for (final f in findings)
            {
              'package': f.package.name,
              'version': f.package.version,
              'dependency': f.package.dependency,
              'id': f.id,
              'aliases': f.aliases,
              'severity': f.severity,
              'summary': f.summary,
              'fixedIn': f.fixedIn,
            },
        ],
      }),
    );
  } else {
    printReport(findings);
  }

  if (outdated) await runOutdated();

  if (findings.isNotEmpty && fix) {
    await runFix(findings);
    // `dart pub upgrade` exits 0 even when a constraint keeps the package
    // where it was, so success is decided by re-checking the new resolution -
    // never by the upgrade's exit code.
    findings = await verifyFix(findings, offline: offline);
  }

  return findings.isEmpty ? 0 : 1;
}

// ── pubspec.lock ─────────────────────────────────────────────────────────────

/// Minimal line-based parser for the `packages:` section of pubspec.lock.
///
/// A YAML dependency just for this would have to be resolved before the audit
/// can run - which is exactly the situation an audit must survive. The lock
/// file format is generated by pub and stable, so scanning it is safe.
List<Package> parseLockFile(String content) {
  final packages = <Package>[];
  final lines = const LineSplitter().convert(content);

  var inPackages = false;
  String? name;
  String? version;
  String? dependency;
  String? source;

  void flush() {
    if (name != null && version != null && source == 'hosted') {
      packages.add(Package(name!, version!, dependency ?? 'transitive'));
    }
    name = version = dependency = source = null;
  }

  for (final line in lines) {
    if (line.startsWith('packages:')) {
      inPackages = true;
      continue;
    }
    if (!inPackages) continue;
    // A top-level key (e.g. "sdks:") ends the packages section.
    if (line.isNotEmpty && !line.startsWith(' ')) {
      flush();
      break;
    }
    final match = RegExp(r'^  (\S+):\s*$').firstMatch(line);
    if (match != null) {
      flush();
      name = match.group(1);
      continue;
    }
    final field = RegExp(r'^    (\w+):\s*"?([^"]*)"?\s*$').firstMatch(line);
    if (field != null) {
      switch (field.group(1)) {
        case 'version':
          version = field.group(2);
        case 'dependency':
          dependency = field.group(2);
        case 'source':
          source = field.group(2);
      }
    }
  }
  flush();
  return packages;
}

// ── OSV.dev ──────────────────────────────────────────────────────────────────

Future<List<Finding>> queryOsv(
  List<Package> packages, {
  bool quiet = false,
}) async {
  if (!quiet) _log('Querying api.osv.dev for known vulnerabilities...');
  final client = HttpClient()..connectionTimeout = const Duration(seconds: 20);
  try {
    final findings = <Finding>[];
    // querybatch returns ids only; details are fetched per hit, which keeps
    // the request small even for a few hundred packages.
    const chunkSize = 100;
    for (var i = 0; i < packages.length; i += chunkSize) {
      final chunk = packages.skip(i).take(chunkSize).toList();
      final body = jsonEncode({
        'queries': [
          for (final p in chunk)
            {
              'package': {'name': p.name, 'ecosystem': 'Pub'},
              'version': p.version,
            },
        ],
      });

      final response = await _post(client, _osvBatchUrl, body);
      final results = (response['results'] as List?) ?? const [];
      for (var j = 0; j < results.length && j < chunk.length; j++) {
        final vulns = (results[j] as Map)['vulns'] as List?;
        if (vulns == null || vulns.isEmpty) continue;
        for (final vuln in vulns) {
          final id = (vuln as Map)['id'] as String;
          findings.add(await _fetchDetails(client, chunk[j], id));
        }
      }
    }
    return findings;
  } finally {
    client.close(force: true);
  }
}

Future<Finding> _fetchDetails(
  HttpClient client,
  Package package,
  String id,
) async {
  Map<String, dynamic> detail;
  try {
    detail = await _get(client, '$_osvVulnUrl$id');
  } on Exception {
    return Finding(
      package: package,
      id: id,
      summary: '(details unavailable)',
      severity: 'UNKNOWN',
      fixedIn: null,
      aliases: const [],
    );
  }

  return Finding(
    package: package,
    id: id,
    summary:
        (detail['summary'] as String?) ??
        (detail['details'] as String?)?.split('\n').first ??
        '(no summary)',
    severity: _severityOf(detail),
    fixedIn: _fixedVersionOf(detail, package.name),
    aliases: [...?(detail['aliases'] as List?)?.cast<String>()],
  );
}

String _severityOf(Map<String, dynamic> detail) {
  final database = detail['database_specific'] as Map?;
  final fromDb = database?['severity'] as String?;
  if (fromDb != null) return fromDb.toUpperCase();
  final severity = detail['severity'] as List?;
  if (severity != null && severity.isNotEmpty) {
    return (severity.first as Map)['type']?.toString() ?? 'UNKNOWN';
  }
  return 'UNKNOWN';
}

/// The first version in which the advisory considers the package fixed.
String? _fixedVersionOf(Map<String, dynamic> detail, String packageName) {
  for (final affected in (detail['affected'] as List?) ?? const []) {
    final pkg = (affected as Map)['package'] as Map?;
    if (pkg?['name'] != packageName) continue;
    for (final range in (affected['ranges'] as List?) ?? const []) {
      for (final event in ((range as Map)['events'] as List?) ?? const []) {
        final fixed = (event as Map)['fixed'];
        if (fixed != null) return fixed.toString();
      }
    }
  }
  return null;
}

Future<Map<String, dynamic>> _post(
  HttpClient client,
  String url,
  String body,
) async {
  final request = await client.postUrl(Uri.parse(url));
  request.headers.contentType = ContentType.json;
  request.write(body);
  final response = await request.close();
  final text = await response.transform(utf8.decoder).join();
  if (response.statusCode != 200) {
    throw HttpException('OSV returned ${response.statusCode}: $text');
  }
  return jsonDecode(text) as Map<String, dynamic>;
}

Future<Map<String, dynamic>> _get(HttpClient client, String url) async {
  final request = await client.getUrl(Uri.parse(url));
  final response = await request.close();
  final text = await response.transform(utf8.decoder).join();
  if (response.statusCode != 200) {
    throw HttpException('OSV returned ${response.statusCode}');
  }
  return jsonDecode(text) as Map<String, dynamic>;
}

// ── output ───────────────────────────────────────────────────────────────────

void printReport(List<Finding> findings) {
  stdout.writeln('');
  if (findings.isEmpty) {
    stdout.writeln('No known vulnerabilities in the resolved dependencies.');
    return;
  }

  stdout.writeln('${findings.length} vulnerability finding(s):');
  stdout.writeln('');
  for (final f in findings) {
    stdout.writeln(
      '  ${f.package.name} ${f.package.version} '
      '(${f.package.dependency})',
    );
    stdout.writeln('    ${f.id}  [${f.severity}]');
    stdout.writeln('    ${_wrap(f.summary, 70, '    ')}');
    if (f.aliases.isNotEmpty) {
      stdout.writeln('    aliases: ${f.aliases.join(', ')}');
    }
    stdout.writeln(
      f.fixedIn != null
          ? '    fixed in: ${f.fixedIn}'
          : '    no fixed version published yet',
    );
    stdout.writeln('    https://osv.dev/vulnerability/${f.id}');
    stdout.writeln('');
  }

  // One package can carry several advisories - bump it once, to the highest
  // fixed version any of them asks for.
  final bumps = <String, String?>{};
  for (final f in findings.where(
    (f) => f.package.dependency.startsWith('direct'),
  )) {
    bumps[f.package.name] = _higherVersion(bumps[f.package.name], f.fixedIn);
  }
  if (bumps.isNotEmpty) {
    stdout.writeln('Direct dependencies to bump in pubspec.yaml:');
    for (final entry in bumps.entries) {
      stdout.writeln('  ${entry.key}: ^${entry.value ?? "?"}');
    }
    stdout.writeln('');
  }
  stdout.writeln(
    'Apply the available upgrades with: '
    'dart tools/audit_deps.dart --fix',
  );
}

/// Returns the higher of two version strings, comparing numeric parts as
/// numbers so "3.10.0" ranks above "3.9.0". Null means "no fix published".
String? _higherVersion(String? a, String? b) {
  if (a == null) return b;
  if (b == null) return a;
  List<int> parts(String v) => [
    for (final part in v.split(RegExp(r'[.+-]'))) int.tryParse(part) ?? 0,
  ];
  final left = parts(a);
  final right = parts(b);
  for (var i = 0; i < left.length && i < right.length; i++) {
    if (left[i] != right[i]) return left[i] > right[i] ? a : b;
  }
  return left.length >= right.length ? a : b;
}

String _wrap(String text, int width, String indent) {
  final words = text.replaceAll('\n', ' ').split(RegExp(r'\s+'));
  final buffer = StringBuffer();
  var lineLength = 0;
  for (final word in words) {
    if (lineLength + word.length > width) {
      buffer.write('\n$indent');
      lineLength = 0;
    }
    buffer.write('$word ');
    lineLength += word.length + 1;
  }
  return buffer.toString().trimRight();
}

void _log(String message) {
  if (!jsonOutput) stdout.writeln(message);
}

// ── actions ──────────────────────────────────────────────────────────────────

Future<void> runOutdated() async {
  _log('');
  _log('=== dart pub outdated ===');
  final result = await Process.run(Platform.isWindows ? 'dart.bat' : 'dart', [
    'pub',
    'outdated',
  ], runInShell: true);
  stdout.write(result.stdout);
}

/// Upgrades the affected packages. Transitive packages have no constraint of
/// their own, so `pub upgrade` on the workspace is the only lever - it lifts
/// them as far as the direct constraints allow.
Future<void> runFix(List<Finding> findings) async {
  final names = {for (final f in findings) f.package.name}.toList()..sort();
  _log('');
  _log('=== upgrading: ${names.join(', ')} ===');

  final result = await Process.run(Platform.isWindows ? 'dart.bat' : 'dart', [
    'pub',
    'upgrade',
    ...names,
  ], runInShell: true);
  stdout.write(result.stdout);
  if (result.exitCode != 0) stderr.write(result.stderr);
}

/// Re-resolves and re-queries OSV, and reports per package what the upgrade
/// actually achieved. Returns the findings that are still open.
Future<List<Finding>> verifyFix(
  List<Finding> before, {
  required bool offline,
}) async {
  final packages = parseLockFile(File('pubspec.lock').readAsStringSync());
  final affected = {for (final f in before) f.package.name};
  final oldVersions = {
    for (final f in before) f.package.name: f.package.version,
  };
  final newVersions = {
    for (final p in packages)
      if (affected.contains(p.name)) p.name: p.version,
  };

  _log('');
  _log('=== result ===');

  if (offline) {
    // Without OSV we can still say what moved, but not whether that is enough.
    for (final name in affected.toList()..sort()) {
      _log('  $name ${oldVersions[name]} -> ${newVersions[name] ?? "(gone)"}');
    }
    _log(
      '  --offline: re-run without it to confirm the advisories are cleared.',
    );
    return before;
  }

  final still = await queryOsv(
    packages.where((p) => affected.contains(p.name)).toList(),
    quiet: true,
  );
  final stillVulnerable = {for (final f in still) f.package.name};

  for (final name in affected.toList()..sort()) {
    final from = oldVersions[name];
    final to = newVersions[name] ?? '(gone)';
    if (!stillVulnerable.contains(name)) {
      _log('  $name $from -> $to  fixed');
    } else if (from == to) {
      _log(
        '  $name $from  UNCHANGED - a constraint is holding it back. '
        'Widen "$name:" in pubspec.yaml, then re-run.',
      );
    } else {
      _log('  $name $from -> $to  still affected (no safe version reachable)');
    }
  }

  if (still.isEmpty) _log('  all findings cleared.');
  return still;
}
